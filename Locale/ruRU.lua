-- Blackthornes Butler -- Locale/ruRU.lua
-- Russian: the words players see, on a Russian client.
--
-- Each line is the English key (exactly as the code writes it) and its
-- Russian. A key with no line here shows in English. The Russian speaks to
-- the player as "ты" and uses the game's words (сумки, предмет, торговец,
-- почтовый ящик, банк, аукцион, распылить, продать, боеприпасы, колчан,
-- задание). A line may name its values by place ("%2$s ... %1$s") where
-- Russian word order needs it; L.Format puts them in order.
--
-- Item, character and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

