-- Blackthornes Butler -- Locale/zhCN.lua
-- Simplified Chinese: the words players see, on a Simplified Chinese client.
--
-- Each line is the English key (exactly as the code writes it) and its
-- Chinese. A key with no line here shows in English. The Chinese speaks to
-- the player plainly and uses the game's own words (背包, 物品, 商人, 邮箱,
-- 银行, 小号, 拍卖行, 分解, 出售, 弹药, 箭袋). A line may name its values
-- by place ("%2$s ... %1$s") where Chinese word order needs it; L.Format
-- puts them in order.
--
-- Item, character and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

